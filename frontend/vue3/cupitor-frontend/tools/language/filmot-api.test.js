import {
  UC_ID, channelsFromCupitorIndex, restrictedChannelGroups, apiSearchParams,
  apiTranscriptLines, apiHit, createFilmotApiClient, resolveCupitorChannels,
  collectFilmotApiWord,
} from './filmot-api.js';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ids = [
  'UCXuqSBlHAE6Xw-yeJA0Tunw', 'UCm_5ChhRbu3Wb9Ccwl3htQw',
  'UCYjOBtLXNluAL4kvtvXclTQ', 'UCcR3L6_69wSH-n0BYvhr7iA',
  'UCv_eLedVo7KT15vpQ0w0RkQ', 'UCuAXFkgsw1L7xaCfnd5JJOw',
];
const vid = ['dQw4w9WgXcQ', 'aQw4w9WgXcQ', 'bQw4w9WgXcQ', 'cQw4w9WgXcQ'];
const config = {
  lang: 'sv', maxItemsPerWord: 2, linesBefore: 1, linesAfter: 1,
  preferManualCaptions: true, apiChannelGroups: 2,
  apiMaxCreditsPerWord: 30, apiUnrestrictedFallback: true,
};
const sampleLines = [
  { s: 3.5, t: 'Jag hör ett ljud.' },
  { s: 5, t: 'Det gäller alla barn.' },
  { s: 7, t: 'Det händer igen.' },
];
const responseRow = (id, name='One', subtitles=sampleLines) => ({
  id, title: 'Example ' + id, channelid: ids[0], channelname: name,
  manualsubs: ' sv ', autosubs: ' en ', subtitles,
});

test('identifies and ranks Cupitor channels using distinct YouTube IDs', () => {
  const index = [
    { name: 'Channel One || Film A || dQw4w9WgXcQ', source: 'YouTube', link: vid[0] },
    { name: 'Channel One || Film A || dQw4w9WgXcQ', source: 'YouTube', link: vid[0] },
    { name: 'Channel Two || Film B || aQw4w9WgXcQ', source: 'YouTube', link: vid[1] },
    { name: 'Channel One || Film C || bQw4w9WgXcQ', source: 'YouTube', link: vid[2] },
    { name: 'Other || Audio || anything', source: 'Spotify', link: vid[3] },
  ];
  expect(channelsFromCupitorIndex(index).map(c => [c.name, c.count])).toEqual([
    ['Channel One', 2], ['Channel Two', 1],
  ]);
  expect(channelsFromCupitorIndex(index, 1)[0].videoIds).toEqual([vid[0], vid[2]]);
});

test('discounted calls always have at most five genuine included IDs', () => {
  expect(ids.every(id => UC_ID.test(id))).toBe(true);
  expect(restrictedChannelGroups(ids.map(channelid => ({ channelid })), 2)).toEqual([
    ids.slice(0, 5), ids.slice(5, 6),
  ]);
  expect(restrictedChannelGroups([{ channelid: 'bad' }])).toEqual([]);
  expect(() => apiSearchParams('gäller', 'sv', ids)).toThrow(/1-5/);
  const params = apiSearchParams('gäller', 'sv', ids.slice(0, 5));
  expect(params.query).toBe('"gäller"');
  expect(params.channelID).toBe(ids.slice(0, 5).join(','));
  expect(params.columns).toMatch(/subtitles/);
  expect(params.perPageCount).toBe(10);
  expect(apiSearchParams('gäller', 'sv')).not.toHaveProperty('channelID');
});

test('API captions preserve timestamps and cross-line regex matching', () => {
  const row = responseRow(vid[0]);
  expect(apiTranscriptLines(row, 'sv')[1]).toEqual({ idx: 1, ts: 5, text: 'Det gäller alla barn.' });
  expect(apiTranscriptLines({
    subtitles: [{ lang: 'en', isauto: 1, transcript: [{s:1,t:'wrong'}] },
      { lang: 'sv', isauto: 0, transcript: sampleLines }],
  }, 'sv')).toHaveLength(3);
  const hit = apiHit(row, 'gäller', /gäller/, config);
  expect(hit).toMatchObject({
    word: 'gäller', videoId: vid[0], tsStart: 5, tsEnd: 7,
    matchIdx: 1, isAutoGenerated: false,
  });
  expect(hit.lines).toHaveLength(3);
  expect(apiHit(responseRow(vid[0], 'One', []), 'gäller', /gäller/, config)).toBeNull();
  expect(apiHit(row, 'saknas', /saknas/, config)).toBeNull();
});

test('resolves exact Cupitor channel names from representative videos, not fuzzy guesses', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'cupitor-fil-api-'));
  try {
    const calls = [];
    const client = {
      get: async (endpoint, params) => {
        calls.push({ endpoint, params });
        return [
          { id: vid[0], channelid: ids[0], channelname: 'Channel One' },
          { id: vid[1], channelid: ids[1], channelname: 'An unrelated channel' },
        ];
      },
    };
    const input = [
      { name: 'Channel One || Video || ' + vid[0], source: 'YouTube', link: vid[0] },
      { name: 'Channel Two || Video || ' + vid[1], source: 'YouTube', link: vid[1] },
    ];
    const file = join(dir, 'channels.json');
    const resolved = await resolveCupitorChannels(input, client, file);
    expect(calls).toHaveLength(1);
    expect(calls[0].endpoint).toBe('getvideos');
    expect(resolved.find(c => c.name === 'Channel One').channelid).toBe(ids[0]);
    expect(resolved.find(c => c.name === 'Channel Two').channelid).toBeNull();
    expect(JSON.parse(readFileSync(file, 'utf8'))).toHaveProperty('channel one', ids[0]);
    await resolveCupitorChannels(input.filter(x => x.name.startsWith('Channel One')), client, file);
    expect(calls).toHaveLength(1);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('restricted searches fill quota without unrestricted search', async () => {
  const calls = [];
  const client = {
    hasCached: () => false,
    get: async (endpoint, params) => {
      calls.push(params);
      return { result: [responseRow(vid[0]), responseRow(vid[1])] };
    },
  };
  const res = await collectFilmotApiWord({
    word: 'gäller', terms: ['gäller'], regex: /gäller/, cfg: config,
    channels: ids.slice(0, 6).map(channelid => ({ channelid })), client,
  });
  expect(res.hits.map(h => h.videoId)).toEqual([vid[0], vid[1]]);
  expect(calls).toHaveLength(1);
  expect(calls[0].channelID).toBe(ids.slice(0, 5).join(','));
  expect(res.plannedCredits).toBe(1);
  expect(res.complete).toBe(true);
});

test('unrestricted search only follows unsuccessful scoped groups and avoids duplicate videos', async () => {
  const calls = [];
  const client = {
    hasCached: () => false,
    get: async (endpoint, params) => {
      calls.push(params);
      if (params.channelID) return { result: [responseRow(vid[0])] };
      return { result: [responseRow(vid[0]), responseRow(vid[1])] };
    },
  };
  const res = await collectFilmotApiWord({
    word: 'gäller', terms: ['gäller'], regex: /gäller/, cfg: config,
    channels: [{ channelid: ids[0] }], client,
  });
  expect(res.hits.map(h => h.videoId)).toEqual([vid[0], vid[1]]);
  expect(calls.map(x => !!x.channelID)).toEqual([true, false]);
  expect(res.complete).toBe(true);
});

test('a conservative credit cap blocks fallback and does not mark incomplete work as done', async () => {
  const calls = [];
  const client = {
    hasCached: () => false,
    get: async (endpoint, params) => { calls.push(params); return { result: [] }; },
  };
  const res = await collectFilmotApiWord({
    word: 'gäller', terms: ['gäller'], regex: /gäller/,
    cfg: { ...config, apiMaxCreditsPerWord: 1 },
    channels: [{ channelid: ids[0] }], client,
  });
  expect(calls).toHaveLength(1);
  expect(res.complete).toBe(false);
  expect(res.plannedCredits).toBe(1);
});

test('API client uses X-API-Key headers (never the URL), caches responses, and fails on 429', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'cupitor-fil-cache-'));
  try {
    const calls = [];
    const fetchFn = async (url, options) => {
      calls.push({ url, headers: options.headers });
      return { ok: true, status: 200, json: async () => ({ result: [] }),
        headers: { get: key => key === 'X-API-Credit-Cost' ? '1' : null } };
    };
    const api = createFilmotApiClient({ key: 'secret-for-test', cacheDir: dir, delayMs: 0, fetchFn });
    const opts = apiSearchParams('gäller', 'sv', [ids[0]]);
    await api.get('getsubtitlesearch', opts);
    await api.get('getsubtitlesearch', opts);
    expect(calls).toHaveLength(1);
    expect(calls[0].headers['X-API-Key']).toBe('secret-for-test');
    expect(calls[0].url).not.toContain('secret-for-test');
    expect(api.hasCached('getsubtitlesearch', opts)).toBe(true);
    const exhausted = createFilmotApiClient({ key: 'key', delayMs: 0, fetchFn: async () => ({ status: 429, ok: false }) });
    await expect(exhausted.get('getsubtitlesearch', opts)).rejects.toMatchObject({ quota: true });
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
