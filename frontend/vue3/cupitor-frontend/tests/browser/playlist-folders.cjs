const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const {serveFixtures}=require('./language-dialogs.cjs')
async function verify(browser,width){
 const mobile=width<700,page=await browser.newPage({viewport:{width,height:900},isMobile:mobile,hasTouch:mobile})
 const errors=[],alerts=[];let promptAnswer=''
 page.setDefaultTimeout(10000)
 page.on('pageerror',e=>errors.push(e.message))
 page.on('dialog',d=>{if(d.type()==='prompt')d.accept(promptAnswer);else{alerts.push(d.message());d.dismiss()}})
 await page.route('**/*',serveFixtures)
 await page.addInitScript(()=>window.dontConfirmOnRefresh=true)
 const click=async selector=>page.locator(selector).click()
 const browse=async()=>{if(!await page.locator('#playlistBrowserPanel').evaluate(el=>el.open))await page.locator('#playlistBrowserPanel > summary').click()}
 const folder=async path=>{
   await browse()
   const details=page.locator('.pl-folder-pane')
   if(!await details.evaluate(el=>el.open))await details.locator('summary').click()
   await page.locator('.pl-folder-list button').filter({has:page.locator('span')}).evaluateAll((els,path)=>els.find(el=>el.dataset.folder===path).click(),path)
 }
 const create=async(name,parent='')=>{
   await browse()
   await click('#playlistNewFolder')
   await page.getByLabel('Folder name',{exact:true}).fill(name)
   await page.getByLabel('Parent folder',{exact:true}).selectOption(parent)
   await page.getByRole('button',{name:'Create folder',exact:true}).click()
 }
 try{
  await page.goto('http://127.0.0.1:3000/language.html',{waitUntil:'networkidle'})
  await page.evaluate(async()=>{
   await Promise.all([window._vocabularyReadyPromise,window._subtitlesReadyPromise])
   const card=(id,source)=>({manual:true,id,source,enabled:true})
   window._recordings={
    'Swedish stories':{items:{Manual:{Card:[card('a','En berättelse')]}}},
    'Spanish words':{items:{Manual:{Card:[card('b','Hola')]}}},
    'Shared example':{items:{},readOnly:true,owner:'alice'},
    'App book':{items:{},external:true,extId:44},
    'Combined':{virtual:true,members:['Swedish stories','Spanish words']},
   }
   window.selectRecording('Swedish stories');window.openRecordingReviewDialog()
  })
  assert.equal(await page.locator('#recReviewBtn').innerText(),'Playlists')
  assert.equal(await page.locator('#recordingReviewDialog').evaluate(el=>$(el).dialog('option','title')),'Playlists')
  assert.equal(await page.locator('.pl-playlist-row').count(),5)
  await page.locator('#playlistFilter').fill('spanish')
  assert.equal(await page.locator('.pl-playlist-row').count(),1)
  await page.locator('#playlistFilter').fill('not here')
  assert.match(await page.locator('.pl-browser-empty').innerText(),/No matching/)
  await page.getByRole('button',{name:'Clear',exact:true}).click()
  await page.locator('#playlistTypeFilter').selectOption('shared')
  assert.equal(await page.locator('.pl-playlist-row').count(),1)
  await page.locator('.pl-playlist-row').click()
  assert.equal(await page.locator('#playlistMove').isDisabled(),true)
  assert.equal(await page.locator('#playlistTypeFilter').inputValue(),'shared','filter survives playlist redraw')
  await browse()
  await page.getByRole('button',{name:'Clear',exact:true}).click()
  await create('Svenska')
  assert.match(await page.locator('.pl-browser-empty').innerText(),/empty/)
  await create('Lyssna','Svenska')
  await folder('*')
  await page.locator('.pl-playlist-row[data-playlist="Swedish stories"]').click()
  await click('#playlistMove')
  await page.getByLabel('Destination folder',{exact:true}).selectOption('Svenska/Lyssna')
  await page.getByRole('button',{name:'Move',exact:true}).click()
  assert.equal(await page.evaluate(()=>window._recordings['Swedish stories'].folder),'Svenska/Lyssna')
  assert.equal(await page.locator('.pl-playlist-row').count(),1)
  await folder('Svenska')
  await page.getByRole('button',{name:'Rename / move folder',exact:true}).click()
  await page.getByLabel('Folder name',{exact:true}).fill('Språk')
  await page.getByRole('button',{name:'Save folder',exact:true}).click()
  assert.equal(await page.evaluate(()=>window._recordings['Swedish stories'].folder),'Språk/Lyssna')
  assert.equal(await page.evaluate(()=>window._recordings['Swedish stories'].items.Manual.Card[0].id),'a')
  await folder('Språk/Lyssna')
  await page.getByRole('button',{name:'Delete folder',exact:true}).click()
  assert.match(alerts.pop(),/Move playlists/)
  promptAnswer='A new lesson'
  await click('#playlistCreate')
  assert.equal(await page.evaluate(()=>window._recordings['A new lesson'].folder),'Språk/Lyssna')
  await folder('*')
  await page.locator('#playlistFilter').fill('lyssna')
  assert.equal(await page.locator('.pl-playlist-row').count(),2,'path filtering finds nested playlists')
  await page.getByRole('button',{name:'Clear',exact:true}).click()
  await create('Empty folder')
  // Reload must retain both an empty folder and assignments without server writes.
  await page.reload({waitUntil:'networkidle'})
  await page.evaluate(()=>window.openRecordingReviewDialog())
  assert.equal(await page.evaluate(()=>window._recordings['Swedish stories'].folder),'Språk/Lyssna')
  await folder('Empty folder')
  assert.match(await page.locator('.pl-browser-empty').innerText(),/empty/)
  await page.getByRole('button',{name:'Delete folder',exact:true}).click()
  assert.equal(await page.locator('.pl-folder-list button[data-folder="Empty folder"]').count(),0)
  await folder('*')
  await page.locator('#playlistFilter').fill('sprak')
  assert.equal(await page.locator('.pl-playlist-row').count(),2,'accent-insensitive path filtering')
  await page.getByRole('button',{name:'Clear',exact:true}).click()
  // Cancelled and colliding folder edits leave the catalog intact.
  await click('#playlistNewFolder')
  await page.getByLabel('Folder name',{exact:true}).fill('Språk')
  await page.getByRole('button',{name:'Create folder',exact:true}).click()
  assert.match(await page.locator('.pl-form-error').innerText(),/already exists/)
  await page.locator('.pl-folder-editor').locator('..').getByRole('button',{name:'Cancel',exact:true}).click()
  await folder('*')
  await page.locator('.pl-playlist-row[data-playlist="Swedish stories"]').click()
  await browse()
  const geometry=await page.locator('#recordingReviewDialog').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}))
  assert(geometry.scroll<=geometry.width+1,JSON.stringify(geometry))
  fs.mkdirSync('test-results/playlist-folders',{recursive:true})
  await page.locator('#recordingReviewDialog').evaluate(el=>el.scrollTop=0)
  await page.screenshot({path:`test-results/playlist-folders/${width}.png`})
  assert.deepEqual(errors,[]);assert.deepEqual(alerts,[])
  console.log(width+'px: folders, nested rename/move, filtering, read-only access, reload and layout passed')
 }finally{await page.close()}
}
;(async()=>{const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH,args:['--no-sandbox']});try{for(const width of [1280,390,320])await verify(browser,width)}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1})
